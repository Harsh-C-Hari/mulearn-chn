#!/usr/bin/env node
/**
 * µLearn CHN — Build Memories Section Markup
 * Generates the 6-frame editorial polaroid collage AND the 11-item community gallery from data/memories.js into index.html.
 * Usage: node scripts/build_memories.js [--check]
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
global.window = {};
require(path.join(root, "data/memories.js"));

const memories = window.MULEARN.memories;
const collage = memories.collage;
const gallery = memories.gallery;

const esc = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function renderCollageFrame(c) {
  const isMain = !!c.isMain;
  const slotCls = `polaroid--${c.slot}`;
  const mainCls = isMain ? " polaroid--main" : "";
  const rot = c.rotation || 0;

  let srcset = `${c.src460} 460w, ${c.src920} 920w`;
  let sizes = "(min-width:1024px) 460px, (min-width:640px) 420px, 92vw";
  let w = 460;
  let h = Math.round(460 / c.aspect);

  if (isMain && c.src1200) {
    srcset = `${c.src460} 460w, ${c.src920} 920w, ${c.src1200} 1200w`;
    sizes = "(min-width:1024px) 780px, (min-width:640px) 600px, 92vw";
    w = 1200;
    h = 680;
  }

  const lines = [
    `        <figure class="polaroid ${slotCls}${mainCls}" data-slot="${esc(c.slot)}" style="--rot:${rot}deg;--ratio:${c.aspect}">`,
    `          <div class="polaroid__photo">`,
    `            <img src="${esc(c.src460)}" srcset="${esc(srcset)}" sizes="${sizes}" width="${w}" height="${h}" alt="${esc(c.alt)}" loading="lazy" decoding="async">`,
    `            <span class="polaroid__badge" aria-hidden="true"><svg class="icon"><use href="#i-image"/></svg></span>`,
    `          </div>`,
    `          <figcaption class="polaroid__caption">`,
    isMain ? `            <span class="tag tag--accent polaroid__featured-tag">Featured moment</span>` : ``,
    `            <strong class="polaroid__label">${esc(c.label)}</strong>`,
    `            <span class="polaroid__desc">${esc(c.caption)}</span>`,
    `          </figcaption>`,
    `          <button type="button" class="polaroid__action" data-lightbox-open="${esc(c.lightboxId)}" aria-haspopup="dialog">`,
    `            <span class="sr-only">View photo: ${esc(c.label)} in lightbox</span>`,
    `          </button>`,
    `        </figure>`
  ].filter(Boolean);

  return lines.join("\n");
}

function buildCollageHtml() {
  const rendered = collage.map(renderCollageFrame).join("\n");
  return (
    `<!-- memories:collage:start (generated by scripts/build_memories.js from data/memories.js: do not edit) -->\n` +
    rendered +
    `\n        <!-- memories:collage:end -->`
  );
}

const CAT_GROUP = {
  "Community": "community",
  "Workshops": "workshops",
  "Design": "design",
  "ODYSSEY": "events",
  "Buildathon": "events",
  "Build with AI": "events",
  "Useless Projects": "events"
};

const CAT_TONE = {
  "Community": "yellow",
  "Workshops": "mint",
  "Design": "lavender",
  "ODYSSEY": "coral",
  "Buildathon": "coral",
  "Build with AI": "coral",
  "Useless Projects": "coral"
};

function renderGalleryCard(g, index) {
  const catGroup = CAT_GROUP[g.category] || "events";
  const tone = CAT_TONE[g.category] || "neutral";

  return [
    `              <li class="gallery-card" data-id="${esc(g.id)}" data-category="${esc(catGroup)}">`,
    `                <article class="card gallery-card__inner" aria-labelledby="${esc(g.id)}-title">`,
    `                  <figure class="gallery-card__thumb">`,
    `                    <img src="${esc(g.src)}" width="${g.width}" height="${g.height}" alt="${esc(g.title)}" loading="lazy" decoding="async">`,
    `                    <span class="gallery-card__badge" aria-hidden="true"><svg class="icon"><use href="#i-image"/></svg></span>`,
    `                  </figure>`,
    `                  <div class="gallery-card__body">`,
    `                    <div class="gallery-card__meta">`,
    `                      <span class="tag tag--sm tag--${tone}">${esc(g.category)}</span>`,
    `                      <span class="gallery-card__dims">${g.width}×${g.height}</span>`,
    `                    </div>`,
    `                    <h4 id="${esc(g.id)}-title" class="gallery-card__title">${esc(g.title)}</h4>`,
    `                    <p class="gallery-card__desc">${esc(g.caption)}</p>`,
    `                  </div>`,
    `                  <button type="button" class="gallery-card__action" data-lightbox-open="${esc(g.id)}" aria-haspopup="dialog">`,
    `                    <span class="sr-only">View photo: ${esc(g.title)} in lightbox</span>`,
    `                  </button>`,
    `                </article>`,
    `              </li>`
  ].join("\n");
}

function buildGalleryHtml() {
  const rendered = gallery.map(renderGalleryCard).join("\n");
  return (
    `<!-- memories:gallery:start (generated by scripts/build_memories.js from data/memories.js: do not edit) -->\n` +
    rendered +
    `\n              <!-- memories:gallery:end -->`
  );
}

const indexPath = path.join(root, "index.html");
let indexContent = fs.readFileSync(indexPath, "utf8");

const startCollage = "<!-- memories:collage:start";
const endCollage = "<!-- memories:collage:end -->";
const startGallery = "<!-- memories:gallery:start";
const endGallery = "<!-- memories:gallery:end -->";

const isCheck = process.argv.includes("--check");

let newContent = indexContent;

// 1. Update Collage
if (newContent.includes(startCollage)) {
  const before = newContent.slice(0, newContent.indexOf(startCollage));
  const after = newContent.slice(newContent.indexOf(endCollage) + endCollage.length);
  newContent = before + buildCollageHtml() + after;
}

// 2. Update Gallery
if (newContent.includes(startGallery)) {
  const before = newContent.slice(0, newContent.indexOf(startGallery));
  const after = newContent.slice(newContent.indexOf(endGallery) + endGallery.length);
  newContent = before + buildGalleryHtml() + after;
} else {
  // If drawer structure not yet in index.html, replace memories__actions placeholder
  const placeholder = '<div class="memories__actions" id="memories-actions"></div>';
  const drawerMarkup = `        <!-- Memories gallery action & drawer (Subphase 7.3) -->
        <div class="memories__actions" id="memories-actions">
          <button type="button" class="btn btn--outline btn--neutral memories__toggle-btn" id="memories-gallery-toggle" aria-expanded="false" aria-controls="memories-gallery" data-js="gallery-toggle">
            <svg class="icon" aria-hidden="true"><use href="#i-image"/></svg>
            <span class="memories__toggle-text">View full gallery (11 photos)</span>
            <svg class="icon memories__toggle-chevron" aria-hidden="true"><use href="#i-arrow-right"/></svg>
          </button>
        </div>

        <div class="memories__drawer" id="memories-gallery" aria-labelledby="memories-gallery-heading" hidden>
          <div class="gallery-panel">
            <div class="gallery-panel__head">
              <div class="gallery-panel__intro">
                <span class="section-label section-label--mint">Community Archive</span>
                <h3 id="memories-gallery-heading" class="gallery-panel__title">All Community <span class="hl">Moments</span></h3>
                <p class="gallery-panel__desc">All 11 authentic photographs and verified event extractions from College of Engineering Chengannur.</p>
              </div>
              <div class="gallery-filters" role="group" aria-label="Filter gallery by category">
                <button type="button" class="btn btn--sm btn--neutral gallery-filter is-active" data-filter="all" aria-pressed="true">All (11)</button>
                <button type="button" class="btn btn--sm btn--neutral gallery-filter" data-filter="community" aria-pressed="false">Community (1)</button>
                <button type="button" class="btn btn--sm btn--neutral gallery-filter" data-filter="workshops" aria-pressed="false">Workshops (4)</button>
                <button type="button" class="btn btn--sm btn--neutral gallery-filter" data-filter="events" aria-pressed="false">Events (5)</button>
                <button type="button" class="btn btn--sm btn--neutral gallery-filter" data-filter="design" aria-pressed="false">Design (1)</button>
              </div>
            </div>

            <ul class="gallery-grid" role="list">
              ${buildGalleryHtml()}
            </ul>
          </div>
        </div>`;

  if (newContent.includes(placeholder)) {
    newContent = newContent.replace(placeholder, drawerMarkup);
  }
}

if (isCheck) {
  if (indexContent !== newContent) {
    console.error("index.html memories markup is out of date. Run: node scripts/build_memories.js");
    process.exit(1);
  }
  console.log("PASS memories collage and gallery markup is up to date");
  process.exit(0);
}

fs.writeFileSync(indexPath, newContent, "utf8");
console.log("Updated index.html with memories collage & gallery markup.");
