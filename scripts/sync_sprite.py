#!/usr/bin/env python3
"""Inject img/ui/sprite.svg into every HTML page between the sprite markers.

Why: external <use href="img/ui/sprite.svg#id"> is blocked on file:// in Chromium, so each page carries an
inline copy. img/ui/sprite.svg stays the single source of truth.

Markers in the HTML (placed right after <body>):
    <!-- sprite:start --> ... <!-- sprite:end -->
Usage: python3 scripts/sync_sprite.py [file.html ...]   (default: index.html, styleguide.html if present)
"""
import re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sprite = open(os.path.join(ROOT, "img/ui/sprite.svg"), encoding="utf-8").read().strip()
sprite = re.sub(r"<!--.*?-->\s*", "", sprite, flags=re.S)          # strip authoring comments
sprite = re.sub(r"\n\s*\n", "\n", sprite)
block = "<!-- sprite:start (generated by scripts/sync_sprite.py — do not edit) -->\n" + sprite + "\n<!-- sprite:end -->"
pat = re.compile(r"<!-- sprite:start.*?<!-- sprite:end -->", re.S)
targets = sys.argv[1:] or [f for f in ("index.html", "styleguide.html") if os.path.exists(os.path.join(ROOT, f))]
for t in targets:
    p = t if os.path.isabs(t) else os.path.join(ROOT, t)
    html = open(p, encoding="utf-8").read()
    if not pat.search(html):
        print(f"SKIP {t}: no sprite markers"); continue
    open(p, "w", encoding="utf-8").write(pat.sub(lambda m: block, html))
    print(f"OK   {t}: sprite synced ({len(sprite)} bytes)")
